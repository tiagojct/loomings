import Foundation
import Testing
@testable import LoomingsShare

@Suite("Share links")
struct ShareLinkTests {
    private struct Fixture: Decodable {
        let name: String
        let text: String
        let payload: String
        let url: String
        let family: String
        let mode: String
    }

    private func stringRepeating(_ value: String, count: Int) -> String {
        String(repeating: value, count: count)
    }

    private func fixtures() throws -> [Fixture] {
        let url = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .appendingPathComponent("Fixtures/share-fixtures.json")
        let data = try Data(contentsOf: url)
        return try JSONDecoder().decode([Fixture].self, from: data)
    }

    @Test("Decodes every payload generated by the web renderer")
    func decodesWebPayloads() throws {
        for fixture in try fixtures() {
            #expect(try ShareLink.decode(fixture.payload) == fixture.text)
        }
    }

    @Test("Decodes full website URLs, including family and mode")
    func decodesWebURLs() throws {
        for fixture in try fixtures() {
            let payload = try ShareLink.parse(string: fixture.url)
            #expect(payload.text == fixture.text)
            #expect(payload.family == fixture.family)
            #expect(payload.mode == fixture.mode)
        }
    }

    @Test("Swift payloads round-trip and Node can decode them")
    func nodeInterop() throws {
        let samples = [
            "",
            "# Hello\n\nA plain document.\n",
            "À noite, *ninguém* escreve — ou escreve? 🐋",
            String(repeating: "Call me Ishmael. ", count: 200),
        ]

        let repo = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent() // LoomingsShareTests
            .deletingLastPathComponent() // Tests
            .deletingLastPathComponent() // macos
            .deletingLastPathComponent() // repo root
        let moduleURL = repo.appendingPathComponent("src/share.js")

        for sample in samples {
            let payload = try ShareLink.encode(sample)
            #expect(payload.hasPrefix("z."))
            #expect(try ShareLink.decode(payload) == sample)

            let script = """
            import { decodeDoc } from '\(moduleURL.absoluteString)';
            let input = '';
            for await (const chunk of process.stdin) input += chunk;
            const text = await decodeDoc(input.trim());
            process.stdout.write(text);
            """
            let process = Process()
            process.executableURL = URL(fileURLWithPath: "/usr/bin/env")
            process.arguments = ["node", "--input-type=module", "-e", script]
            let input = Pipe()
            let output = Pipe()
            let errors = Pipe()
            process.standardInput = input
            process.standardOutput = output
            process.standardError = errors
            try process.run()
            input.fileHandleForWriting.write(Data(payload.utf8))
            try input.fileHandleForWriting.close()
            process.waitUntilExit()

            let data = output.fileHandleForReading.readDataToEndOfFile()
            let decoded = String(data: data, encoding: .utf8)
            #expect(decoded == sample, "Node could not decode a Swift payload")
            if process.terminationStatus != 0 {
                let message = String(
                    data: errors.fileHandleForReading.readDataToEndOfFile(),
                    encoding: .utf8
                ) ?? ""
                Issue.record("node failed: \(message)")
            }
        }
    }

    @Test("URLs stay on the website and carry optional appearance")
    func generatedURL() throws {
        let url = try ShareLink.url(
            for: "# Hi",
            family: "goney",
            mode: "dark"
        )
        #expect(url.host == "loomings.tiagojacinto.eu")
        #expect(url.absoluteString.hasPrefix("https://loomings.tiagojacinto.eu/app/"))
        #expect(url.absoluteString.contains("#d=z."))
        #expect(url.fragment?.hasPrefix("d=z.") == true)
        #expect(url.query?.contains("theme=goney") == true)
        #expect(url.query?.contains("mode=dark") == true)
        #expect(try ShareLink.parse(url).text == "# Hi")
    }

    @Test("Malformed and oversized payloads fail safely")
    func malformed() throws {
        #expect(throws: ShareLinkError.self) { try ShareLink.decode("nope") }
        #expect(throws: ShareLinkError.self) { try ShareLink.decode("x.abc") }
        #expect(throws: ShareLinkError.self) { try ShareLink.decode("z.!!!!") }

        let oversized = "p." + String(repeating: "A", count: ShareLink.maximumPayloadLength + 1)
        #expect(throws: ShareLinkError.tooLarge) { try ShareLink.decode(oversized) }

        let bomb = stringRepeating("A", count: ShareLink.maximumDecodedLength + 1)
        let compressedBomb = try ShareLink.encode(bomb)
        #expect(throws: ShareLinkError.tooLarge) {
            try ShareLink.decode(compressedBomb)
        }

        #expect(throws: ShareLinkError.notShareLink) {
            try ShareLink.parse(URL(string: "https://example.com/")!)
        }
        #expect(throws: ShareLinkError.notShareLink) {
            try ShareLink.parse(URL(string: "https://example.com/app/#heading")!)
        }
    }
}
